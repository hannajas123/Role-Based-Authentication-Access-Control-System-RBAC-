

import csv

from django.http import HttpResponse
from django.shortcuts import get_object_or_404

from rest_framework.views import APIView
from rest_framework.response import Response
from rest_framework import status
from rest_framework.permissions import IsAuthenticated
from rest_framework.exceptions import PermissionDenied

from roles.permissions import HasModulePermission
from .models import Report
from .serializers import ReportSerializer

# Create your views here.

def allowed_report_types(user):
    if user.is_superuser or (
        user.role and user.role.name == "Administrator"
    ):
        return ["employee", "financial"]

    if user.role and user.role.name == "HR Manager":
        return ["employee"]

    if user.role and user.role.name == "Finance Manager":
        return ["financial"]

    return []


class ReportListView(APIView):
    permission_classes = [IsAuthenticated, HasModulePermission]
    required_module = "Reports"

    def get(self, request):
        report_types = allowed_report_types(request.user)

        reports = Report.objects.filter(
            report_type__in=report_types
        ).select_related("generated_by")

        serializer = ReportSerializer(reports, many=True)
        return Response(serializer.data)


class GenerateReportView(APIView):
    permission_classes = [IsAuthenticated, HasModulePermission]
    required_module = "Reports"
    required_action = "Generate"

    def post(self, request):
        title = request.data.get("title")
        report_type = request.data.get("report_type")

        if not title or report_type not in ["employee", "financial"]:
            return Response(
                {"error": "Provide a title and valid report_type."},
                status=status.HTTP_400_BAD_REQUEST
            )

        if report_type not in allowed_report_types(request.user):
            raise PermissionDenied(
                "You cannot generate this type of report."
            )

        report = Report.objects.create(
            title=title,
            report_type=report_type,
            generated_by=request.user
        )

        return Response(
            ReportSerializer(report).data,
            status=status.HTTP_201_CREATED
        )


class DownloadReportView(APIView):
    permission_classes = [IsAuthenticated, HasModulePermission]
    required_module = "Reports"
    required_action = "Download"

    def get(self, request, pk):
        report = get_object_or_404(Report, pk=pk)

        if report.report_type not in allowed_report_types(request.user):
            raise PermissionDenied(
                "You cannot download this report."
            )

        response = HttpResponse(content_type="text/csv")
        response["Content-Disposition"] = (
            f'attachment; filename="report_{report.id}.csv"'
        )

        writer = csv.writer(response)
        writer.writerow(["Report ID", "Title", "Type", "Generated By"])
        writer.writerow([
            report.id,
            report.title,
            report.report_type,
            report.generated_by.username,
        ])

        return response
