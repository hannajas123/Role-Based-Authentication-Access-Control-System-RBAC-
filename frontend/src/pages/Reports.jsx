
import { useEffect, useState } from "react";
import api from "../services/api";
import { hasPermission } from "../services/permissions";

function Reports({ user }) {
  const [reports, setReports] = useState([]);
  const [title, setTitle] = useState("");
  const [reportType, setReportType] = useState("employee");
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");
  const [message, setMessage] = useState("");

  const canView = hasPermission(user, "Reports", "View");
  const canGenerate = hasPermission(user, "Reports", "Generate");
  const canDownload = hasPermission(user, "Reports", "Download");

  const loadReports = async () => {
    try {
      setLoading(true);
      setError("");

      const response = await api.get("reports/");
      setReports(response.data);
    } catch (err) {
      setError(
        JSON.stringify(err.response?.data || "Unable to load reports.")
      );
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    if (canView) {
      loadReports();
    } else {
      setLoading(false);
    }
  }, []);

  const handleGenerate = async (e) => {
    e.preventDefault();
    setError("");
    setMessage("");

    try {
      await api.post("reports/generate/", {
        title,
        report_type: reportType,
      });

      setTitle("");
      setMessage("Report generated successfully!");

      await loadReports();
    } catch (err) {
      setError(
        JSON.stringify(err.response?.data || "Unable to generate report.")
      );
    }
  };

  const handleDownload = async (report) => {
    try {
      const response = await api.get(
        `reports/${report.id}/download/`,
        { responseType: "blob" }
      );

      const fileURL = window.URL.createObjectURL(
        new Blob([response.data], { type: "text/csv" })
      );

      const link = document.createElement("a");
      link.href = fileURL;
      link.download = `report-${report.id}.csv`;

      document.body.appendChild(link);
      link.click();
      link.remove();

      window.URL.revokeObjectURL(fileURL);
    } catch (err) {
      setError("Unable to download report. Check your permissions.");
    }
  };

  if (!canView) {
    return (
      <div className="content-card">
        <h2>Access Denied</h2>
        <p>You cannot view reports.</p>
      </div>
    );
  }

  if (loading) return <p>Loading reports...</p>;

  return (
    <div className="content-card">
      <h2>Reports Management</h2>

      {error && <p className="error">{error}</p>}
      {message && <p className="success-message">{message}</p>}

      {canGenerate && (
        <form className="report-form" onSubmit={handleGenerate}>
          <h3>Generate New Report</h3>

          <input
            type="text"
            placeholder="Report Title"
            value={title}
            onChange={(e) => setTitle(e.target.value)}
            required
          />

          <select
            value={reportType}
            onChange={(e) => setReportType(e.target.value)}
          >
            <option value="employee">Employee Report</option>
            <option value="financial">Financial Report</option>
          </select>

          <button type="submit">Generate Report</button>
        </form>
      )}

      <h3>Available Reports</h3>

      <div className="table-wrapper">
        <table>
          <thead>
            <tr>
              <th>ID</th>
              <th>Title</th>
              <th>Type</th>
              <th>Generated By</th>
              <th>Created At</th>
              <th>Action</th>
            </tr>
          </thead>

          <tbody>
            {reports.map((report) => (
              <tr key={report.id}>
                <td>{report.id}</td>
                <td>{report.title}</td>
                <td>{report.report_type}</td>
                <td>{report.generated_by_username}</td>
                <td>{new Date(report.created_at).toLocaleString()}</td>
                <td>
                  {canDownload && (
                    <button onClick={() => handleDownload(report)}>
                      Download CSV
                    </button>
                  )}
                </td>
              </tr>
            ))}

            {reports.length === 0 && (
              <tr>
                <td colSpan="6">No reports available.</td>
              </tr>
            )}
          </tbody>
        </table>
      </div>
    </div>
  );
}

export default Reports;
